import { describe, expect, it } from 'vitest'
import { OverlayInteraction } from '../../../QingToolbox.Tauri/native-launcher/ui-src/src/overlayInteraction'

describe('Launcher overlay dismissal', () => {
  it('requires a complete blank-area click', () => {
    const overlay = new OverlayInteraction()
    expect(overlay.end(1, 10, 10, true, 100)).toBe(false)
    overlay.begin(1, 10, 10, true, 100)
    expect(overlay.end(1, 12, 10, true, 110)).toBe(true)
    overlay.begin(1, 10, 10, false, 120)
    expect(overlay.end(1, 10, 10, true, 130)).toBe(false)
    overlay.begin(1, 10, 10, true, 140)
    expect(overlay.end(1, 10, 10, false, 150)).toBe(false)
  })
  it('does not mistake movement, cancellation, or another pointer for a click', () => {
    const overlay = new OverlayInteraction()
    overlay.begin(1, 10, 10, true, 100)
    expect(overlay.end(1, 30, 10, true, 110)).toBe(false)
    overlay.begin(1, 10, 10, true, 120)
    expect(overlay.end(2, 10, 10, true, 130)).toBe(false)
    overlay.begin(1, 10, 10, true, 140)
    overlay.cancel()
    expect(overlay.end(1, 10, 10, true, 150)).toBe(false)
  })
  it('keeps external drag, file import, and the release gesture visible', () => {
    const overlay = new OverlayInteraction()
    overlay.begin(1, 10, 10, true, 100)
    overlay.externalDrag(true, 110)
    expect(overlay.end(1, 10, 10, true, 120)).toBe(false)
    overlay.begin(1, 10, 10, true, 10000)
    expect(overlay.end(1, 10, 10, true, 10010)).toBe(false)
    overlay.externalDrag(false, 10100)
    overlay.begin(1, 10, 10, true, 10110)
    expect(overlay.end(1, 10, 10, true, 10120)).toBe(false)
    overlay.begin(1, 10, 10, true, 10800)
    expect(overlay.end(1, 10, 10, true, 10810)).toBe(true)
  })
  it('does not hide when an internal icon is released outside the panel', () => {
    const overlay = new OverlayInteraction()
    overlay.internalDrag(true, 100)
    overlay.begin(1, 10, 10, true, 110)
    expect(overlay.end(1, 10, 10, true, 120)).toBe(false)
    overlay.internalDrag(false, 130)
    overlay.begin(1, 10, 10, true, 140)
    expect(overlay.end(1, 10, 10, true, 150)).toBe(false)
    overlay.begin(1, 10, 10, true, 600)
    expect(overlay.end(1, 10, 10, true, 610)).toBe(true)
  })
})
